import sys,argparse,math
from pathlib import Path
sys.path.insert(0,str(Path(__file__).resolve().parents[1]))
from common import *
p=argparse.ArgumentParser();p.add_argument('--p',type=int,default=61);p.add_argument('--q',type=int,default=53);p.add_argument('--e',type=int,default=17);p.add_argument('--m',type=int,default=65)
a=p.parse_args()
if not(3<=a.p<=100000 and 3<=a.q<=100000 and prime(a.p) and prime(a.q) and a.p!=a.q): p.error('p,q phải nguyên tố khác nhau từ 3..100000')
n=a.p*a.q;phi=(a.p-1)*(a.q-1)
if not(1<a.e<phi and math.gcd(a.e,phi)==1):p.error('Cần 1<e<phi và gcd(e,phi)=1')
if not 0<=a.m<n:p.error('Cần 0<=m<n')
print('BOB TẠO KHÓA — textbook RSA dùng để học')
print(f'p={a.p}, q={a.q}; n=pq={n}; phi=(p-1)(q-1)={phi}')
print(f'Chọn e={a.e}; gcd(e,phi)={math.gcd(a.e,phi)}')
write('public_key.json',{'n':n,'e':a.e})
print(f'PUBLIC KEY (n,e)=({n},{a.e}) -> data/public_key.json')
print('PRIVATE KEY: giải ed ≡ 1 (mod phi) bằng Euclid mở rộng:')
d=inverse(a.e,phi)
print(f'ed={a.e*d}=1+{(a.e*d-1)//phi} × {phi}')
write('private_key.json',{'n':n,'d':d,'p':a.p,'q':a.q,'phi':phi})
print(f'PRIVATE KEY (n,d)=({n},{d}) -> data/private_key.json')
c=pow(a.m,a.e,n)
print(f'Alice mã hóa: c=m^e mod n={a.m}^{a.e} mod {n}={c}')
write('challenge.json',{'ciphertext':c})
write('bob_expected.json',{'message':a.m})
print('challenge.json chỉ chứa c; bản rõ kiểm chứng chỉ Bob giữ trong bob_expected.json.')
